export function getDeleteConfirm(type, data = {}) {
  switch (type) {
    case 'student':
      return {
        title: 'Удалить ученика?',
        message: 'Вы точно уверены? Будет удалено безвозвратно:',
        items: [
          'Вся статистика практики, прогнозы и стрики',
          'Результаты домашних заданий и ответы',
          'Участие и ответы во всех викторинах',
          'Привязки к предметам и срокам доступа',
        ],
        entityName: data.name,
      };
    case 'topic':
      return {
        title: 'Удалить раздел практики?',
        message: 'Вы точно уверены? Вместе с разделом будут удалены:',
        items: [
          data.questionCount != null
            ? `Все вопросы раздела (${data.questionCount})`
            : 'Все вопросы раздела',
          'Лучшие результаты учеников по этой теме',
          'Связанная статистика попыток',
        ],
        entityName: data.name,
      };
    case 'quiz':
      return {
        title: 'Удалить викторину?',
        message: 'Вы точно уверены? Будет удалено безвозвратно:',
        items: [
          'Сама викторина и все её вопросы',
          'Список участников и их баллы',
          'Все ответы учеников на эту викторину',
        ],
        entityName: data.name,
      };
    default:
      return {
        title: 'Подтвердите удаление',
        message: 'Вы точно уверены? Это действие нельзя отменить.',
        items: [],
        entityName: data.name,
      };
  }
}
